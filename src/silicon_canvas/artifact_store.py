"""Owned local MCP artifacts; callers supply handles, never filesystem paths."""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import uuid
from typing import Any

HANDLE = re.compile(r"[0-9a-f]{32}\Z")
FIGURE = re.compile(r"[A-Za-z0-9_-]{1,80}\Z")
MAX_RECORD_BYTES = 16 * 1024 * 1024


def default_directory() -> Path:
    configured = os.environ.get("SILICON_CANVAS_OUTPUT_DIR", "").strip()
    if configured:
        return Path(configured).expanduser()
    if os.name == "nt":
        return Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData/Local")) / "SiliconCanvas" / "artifacts"
    return Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "silicon-canvas" / "artifacts"


class ArtifactStore:
    def __init__(self, directory: Path | None = None):
        self.root = (directory or default_directory()).expanduser().resolve()

    def _directory(self, artifact_id: str) -> Path:
        if not isinstance(artifact_id, str) or not HANDLE.fullmatch(artifact_id):
            raise ValueError("Invalid artifact handle. Use an artifact_id returned by Silicon Canvas.")
        directory = self.root / artifact_id
        if directory.is_symlink() or not directory.resolve().is_relative_to(self.root):
            raise ValueError("Artifact location is invalid.")
        return directory

    def path(self, artifact_id: str, name: str) -> Path:
        # Names are generated by this module or validated figure IDs, never paths.
        if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z0-9_.-]{1,120}", name) or name in {".", ".."}:
            raise ValueError("Invalid artifact filename.")
        directory = self._directory(artifact_id)
        path = directory / name
        if path.is_symlink() or not path.resolve().is_relative_to(directory.resolve()):
            raise ValueError("Artifact file location is invalid.")
        return path

    def create(self, kind: str, payload: dict[str, Any]) -> str:
        self.root.mkdir(parents=True, exist_ok=True)
        artifact_id = uuid.uuid4().hex
        self._directory(artifact_id).mkdir(mode=0o700)
        self.write(artifact_id, "record.json", json.dumps({"format": "silicon-canvas-artifact-v1", "kind": kind, "payload": payload}, ensure_ascii=False).encode("utf-8"))
        return artifact_id

    def write(self, artifact_id: str, name: str, data: bytes) -> Path:
        directory = self._directory(artifact_id)
        if not directory.is_dir():
            raise ValueError("Artifact does not exist. Generate or compile a new one.")
        path = self.path(artifact_id, name)
        # Same-directory exclusive temporary file makes simultaneous exports atomic.
        temporary = directory / (".write-" + uuid.uuid4().hex)
        try:
            with temporary.open("xb") as handle:
                handle.write(data)
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)
        return path

    def read(self, artifact_id: str, kind: str) -> dict[str, Any]:
        path = self.path(artifact_id, "record.json")
        try:
            if path.stat().st_size > MAX_RECORD_BYTES:
                raise ValueError("Artifact record exceeds the size limit.")
            record = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError):
            raise ValueError("Artifact is unavailable. Generate or compile a new one.") from None
        if not isinstance(record, dict) or record.get("format") != "silicon-canvas-artifact-v1" or record.get("kind") != kind or not isinstance(record.get("payload"), dict):
            raise ValueError("Artifact type does not match this operation.")
        return record["payload"]

    @staticmethod
    def figure_name(figure_id: str, suffix: str) -> str:
        if not isinstance(figure_id, str) or not FIGURE.fullmatch(figure_id):
            raise ValueError("Invalid figure ID.")
        if suffix not in {"guide.png", "review.json", "prompt.txt", "caption.txt"}:
            raise ValueError("Invalid figure asset.")
        return figure_id + "." + suffix

    @staticmethod
    def uri(artifact_id: str, asset: str) -> str:
        if not HANDLE.fullmatch(artifact_id):
            raise ValueError("Invalid artifact handle.")
        return "silicon://artifacts/" + artifact_id + "/" + asset
